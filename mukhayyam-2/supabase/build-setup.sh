#!/usr/bin/env bash
# Joins the migrations and the starting data into supabase/setup.sql: the one file pasted into
# Supabase > SQL Editor when the project is new. Run again after changing any migration.
set -euo pipefail
root="$(cd "$(dirname "$0")" && pwd)"
out="$root/setup.sql"

{
  cat <<'EOF'
-- =====================================================================
--  نظام مخيم 2: تجهيز قاعدة البيانات (مرة واحدة فقط)
--  Supabase > SQL Editor > New query: الصق هذا الملف كاملاً ثم اضغط Run.
--  النتيجة المتوقعة في الأسفل: Success. No rows returned
-- =====================================================================
-- Mukhayyam 2 database setup, generated by supabase/build-setup.sh. Do not edit by hand.

do $$
begin
  if to_regclass('public.employees') is not null then
    raise exception 'قاعدة البيانات مجهزة من قبل، لا داعي لتشغيل هذا الملف مرة ثانية (already set up)';
  end if;
end $$;

EOF
  for f in "$root"/migrations/*.sql "$root/seed.sql"; do
    printf '\n-- ===================== %s =====================\n\n' "$(basename "$f")"
    cat "$f"
  done
  cat <<'EOF'

-- ===================== final check =====================
-- Makes sure Supabase lets this database create sign-in accounts, without keeping anything.
do $$
begin
  begin
    perform public.save_login_account(null, '0500000000', '000000');
    raise exception 'check_passed';
  exception when others then
    if sqlerrm <> 'check_passed' then
      raise exception 'Supabase refused to create sign-in accounts: %', sqlerrm;
    end if;
  end;
end $$;

-- Tell the Data API about the new tables right away.
notify pgrst, 'reload schema';
EOF
} > "$out"

echo "wrote $out ($(wc -l < "$out") lines)"
